/// [ZSTD_DICTIONARY] prepared once for decompressing, instead of on every dump.
static ZSTD_DECODER_DICTIONARY: LazyLock<DecoderDictionary<'static>> =
    LazyLock::new(|| DecoderDictionary::copy(ZSTD_DICTIONARY));

/// Options for displaying a plan dump.
#[derive(Debug, Clone)]
pub struct DisplayPlanDumpOptions {
    /// The stage id to visualize. If none passed, the tree of stages is rendered.
    stage_id: Option<usize>,
    /// Whether to color the output with ANSI escape codes.
    color: bool,
    /// Whether metrics are displayed per task or aggregated across all tasks.
    metrics_format: DistributedMetricsFormat,
    /// If not empty, only the metrics whose name contains one of these are displayed.
    metric_filters: Vec<String>,
    /// Whether metric names must be equal to a filter instead of containing it.
    exact_metric_filters: bool,
    /// Whether the metrics of every node are displayed added up into totals for the whole query.
    totals: bool,
}

impl Default for DisplayPlanDumpOptions {
    fn default() -> Self {
        Self {
            stage_id: None,
            color: false,
            metrics_format: DistributedMetricsFormat::PerTask,
            metric_filters: vec![],
            exact_metric_filters: false,
            totals: false,
        }
    }
}

impl DisplayPlanDumpOptions {
    /// Renders the nodes of this stage with their metrics instead of the tree of stages. The head
    /// of the plan, run by the coordinator, is stage 0.
    pub fn with_stage_id(mut self, stage_id: usize) -> Self {
        self.stage_id = Some(stage_id);
        self
    }

    /// Colors the output with ANSI escape codes, for displaying it in a terminal.
    pub fn with_color(mut self, color: bool) -> Self {
        self.color = color;
        self
    }

    /// Displays metrics per task, like `output_rows={0:10, 1:7}`, which is the default, or
    /// aggregated across all tasks, like `output_rows=17`, which is shorter but hides how the work
    /// was spread across tasks.
    pub fn with_metrics_format(mut self, metrics_format: DistributedMetricsFormat) -> Self {
        self.metrics_format = metrics_format;
        self
    }

    /// Displays only the metrics whose name contains `filter`, like `bytes` for `output_bytes`
    /// and `spilled_bytes`. Adding several filters displays the metrics matching any of them.
    pub fn with_metric_filter(mut self, filter: impl Into<String>) -> Self {
        self.metric_filters.push(filter.into());
        self
    }

    /// Matches metric names that are equal to a filter, instead of the ones containing it, like
    /// `cargo test -- --exact` does with test names: `output_bytes` then leaves out
    /// `estimated_output_bytes`.
    pub fn with_exact_metric_filters(mut self, exact: bool) -> Self {
        self.exact_metric_filters = exact;
        self
    }

    /// Displays the metrics reported by every node of the query added up into totals, like the CPU
    /// time it took, instead of the plan. Each metric is added up its own way, like counts being
    /// summed and maximums keeping the biggest value. Metrics derived for displaying stages are
    /// left out, as they are computed from the nodes' own. With [Self::with_stage_id], the totals
    /// are those of the nodes of that stage only, and with [Self::with_metric_filter], only the
    /// totals of the matching metrics are displayed.
    pub fn with_totals(mut self, totals: bool) -> Self {
        self.totals = totals;
        self
    }

    fn matches_metric_filters(&self, name: &str) -> bool {
        let mut filters = self.metric_filters.iter();
        match self.exact_metric_filters {
            true => filters.any(|filter| name == filter),
            false => filters.any(|filter| name.contains(filter.as_str())),
        }
    }
}

/// Displays a plan dump generated by [generate_plan_dump](crate::generate_plan_dump). See
/// [DisplayPlanDumpOptions] for different types of rendering.
///
/// This is the function used by DFD's CLI for displaying plan dumps in the terminal.
pub fn display_plan_dump(plan: String, opts: DisplayPlanDumpOptions) -> Result<String> {
    let compressed = STANDARD
        .decode(plan.trim())
        .map_err(|err| exec_datafusion_err!("Plan dump is not valid base64: {err}"))?;
    let mut encoded = vec![];
    zstd::stream::Decoder::with_prepared_dictionary(
        compressed.as_slice(),
        &ZSTD_DECODER_DICTIONARY,
    )
    .and_then(|mut decoder| decoder.read_to_end(&mut encoded))
    .map_err(|err| exec_datafusion_err!("Plan dump is not zstd-compressed: {err}"))?;
    let head = StageDump::decode(encoded.as_slice())
        .map_err(|err| exec_datafusion_err!("Plan dump does not contain a plan: {err}"))?;

    // Totals add up the metrics the nodes reported, which the derived ones would count twice.
    let derive_metrics = !opts.totals;
    let mut head = decode_stage(head, None, derive_metrics)?;
    // Metrics are filtered once decoded, so that the metrics derived from them do not depend on
    // the filters.
    if !opts.metric_filters.is_empty() {
        filter_stage_metrics(&mut head, &|name| opts.matches_metric_filters(name));
    }

    let paint = Paint(opts.color);
    let format = opts.metrics_format;
    let single_node = input_stages(&head).is_empty();
    let tree = match (opts.stage_id, &head.plan) {
        // Without a stage filter, the totals are those of the whole query.
        (None, _) if opts.totals => totals_node(all_stages(&head), paint),
        (Some(id), _) if opts.totals => {
            let Some(stage) = find_stage(&head, id as u64) else {
                return exec_err!("Stage {id} not found in the plan dump");
            };
            totals_node(vec![stage], paint)
        }
        // A plan without stages is a single-node plan, which is displayed as its nodes.
        (None | Some(HEAD_STAGE_ID), Some(plan)) if single_node => {
            operator_tree(plan, format, paint)
        }
        (None, _) => stage_tree(&head, format, paint),
        (Some(id), _) => {
            let Some(stage) = find_stage(&head, id as u64) else {
                return exec_err!("Stage {id} not found in the plan dump");
            };
            let mut node = stage_node(stage, format, paint);
            if let Some(plan) = &stage.plan {
                node.children.push(operator_tree(plan, format, paint));
            }
            node
        }
    };
    let mut out = String::new();
    tree.render("", "", paint, &mut out)
        .map_err(|err| internal_datafusion_err!("Failed to render plan dump: {err}"))?;
    Ok(out)
}

/// A stage of a plan dump, with its metrics decoded for displaying them.
pub(super) struct DecodedStage {
    pub(super) id: u64,
    pub(super) tasks: u64,
    pub(super) partitions: u64,
    /// The kind of network boundary reading the stage, like `Shuffle`, which the head stage does
    /// not have.
    pub(super) boundary_kind: Option<String>,
    /// The stage's own metrics, and the ones derived for it.
    pub(super) metrics: MetricsSet,
    pub(super) plan: Option<DecodedPlan>,
}

/// A node of a plan dump, with its metrics decoded for displaying them.
pub(super) struct DecodedPlan {
    pub(super) display: String,
    pub(super) metrics: MetricsSet,
    pub(super) children: Vec<DecodedPlan>,
    /// For network boundaries, the stage they read from. Its plan is not part of `children`.
    pub(super) input_stage: Option<Box<DecodedStage>>,
}

/// Decodes a stage read by `boundary`, a network boundary with its display and metrics, and adds
/// the metrics derived for it if `derive_metrics`.
fn decode_stage(
    stage: StageDump,
    boundary: Option<(&str, &MetricsSet)>,
    derive_metrics: bool,
) -> Result<DecodedStage> {
    let mut decoded = DecodedStage {
        id: stage.stage_id,
        tasks: stage.tasks,
        partitions: stage.partitions,
        boundary_kind: boundary.map(|(display, _)| boundary_kind(display).to_string()),
        metrics: undump_metrics(&stage.metrics)?,
        plan: (stage.plan_dump)
            .map(|plan| decode_plan(*plan, derive_metrics))
            .transpose()?,
    };
    if !derive_metrics {
        return Ok(decoded);
    }
    for metric in stage_derived_metrics(&decoded, boundary.map(|(_, metrics)| metrics)) {
        decoded.metrics.push(metric);
    }
    Ok(decoded)
}

fn decode_plan(plan: PlanDump, derive_metrics: bool) -> Result<DecodedPlan> {
    let metrics = undump_metrics(&plan.metrics)?;
    let input_stage = match plan.input_stage {
        Some(stage) => Some(Box::new(decode_stage(
            *stage,
            Some((&plan.display, &metrics)),
            derive_metrics,
        )?)),
        None => None,
    };
    Ok(DecodedPlan {
        children: plan
            .children
            .into_iter()
            .map(|child| decode_plan(child, derive_metrics))
            .collect::<Result<_>>()?,
        display: plan.display,
        metrics,
        input_stage,
    })
}

/// Leaves only the metrics whose name `matches`, in `stage`, in its nodes and in the stages it
/// reads from.
fn filter_stage_metrics(stage: &mut DecodedStage, matches: &dyn Fn(&str) -> bool) {
    stage.metrics = matching_metrics(&stage.metrics, matches);
    if let Some(plan) = &mut stage.plan {
        filter_plan_metrics(plan, matches);
    }
}

fn filter_plan_metrics(plan: &mut DecodedPlan, matches: &dyn Fn(&str) -> bool) {
    plan.metrics = matching_metrics(&plan.metrics, matches);
    for child in &mut plan.children {
        filter_plan_metrics(child, matches);
    }
    if let Some(stage) = &mut plan.input_stage {
        filter_stage_metrics(stage, matches);
    }
}

fn matching_metrics(metrics: &MetricsSet, matches: &dyn Fn(&str) -> bool) -> MetricsSet {
    let mut matching = MetricsSet::new();
    for metric in metrics.iter() {
        if matches(metric.value().name()) {
            matching.push(Arc::clone(metric));
        }
    }
    matching
}

/// Reverses how a dump stores metrics, as one column per metric, giving each metric of a column
/// its task label back.
fn undump_metrics(columns: &[pb::MetricColumn]) -> Result<MetricsSet> {
    let mut metrics = MetricsSet::new();
    for column in columns {
        let Some(template) = &column.metric else {
            continue;
        };
        let width = metric_values(&mut template.clone())?.len();
        if column.values.len() != column.tasks.len() * width {
            return exec_err!("Plan dump has a metric column with a wrong number of values");
        }
        for (task, values) in column.tasks.iter().zip(column.values.chunks_exact(width)) {
            let mut metric = template.clone();
            for (slot, value) in metric_values(&mut metric)?.into_iter().zip(values) {
                *slot = *value;
            }
            metric.labels.push(pb::Label {
                name: DISTRIBUTED_DATAFUSION_TASK_ID_LABEL.to_string(),
                value: task.to_string(),
            });
            metrics.push(metric_proto_to_df(metric)?);
        }
    }
    Ok(metrics)
}

/// A node of a rendered plan dump: a label followed by one line per metric, and its children.
struct Node {
    label: String,
    metrics: Vec<String>,
    children: Vec<Node>,
}

impl Node {
    fn render(
        &self,
        prefix: &str,
        child_prefix: &str,
        paint: Paint,
        out: &mut String,
    ) -> std::fmt::Result {
        writeln!(out, "{}{}", paint.dim(prefix), self.label)?;
        let guide = match self.children.is_empty() {
            true => "  ",
            false => "│ ",
        };
        let metric_prefix = paint.dim(&format!("{child_prefix}{guide}"));
        for metric in &self.metrics {
            writeln!(out, "{metric_prefix}{metric}")?;
        }
        for (i, child) in self.children.iter().enumerate() {
            let (branch, continuation) = match i == self.children.len() - 1 {
                true => ("└─ ", "   "),
                false => ("├─ ", "│  "),
            };
            child.render(
                &format!("{child_prefix}{branch}"),
                &format!("{child_prefix}{continuation}"),
                paint,
                out,
            )?;
        }
        Ok(())
    }
}

/// A stage with its metrics.
fn stage_node(stage: &DecodedStage, format: DistributedMetricsFormat, paint: Paint) -> Node {
    let label = match (stage.id, &stage.boundary_kind) {
        (0, None) => paint.stage("DistributedExec"),
        (id, boundary_kind) => {
            let boundary_kind = (boundary_kind.as_ref())
                .map(|kind| format!(" {}", paint.boundary(&format!("({kind})"))))
                .unwrap_or_default();
            let tasks = paint.metric(&format!("tasks={}", stage.tasks));
            let partitions = paint.metric(&format!("partitions={}", stage.partitions));
            format!(
                "{}{boundary_kind} {tasks} {partitions}",
                paint.stage(&format!("Stage {id}"))
            )
        }
    };
    Node {
        label,
        metrics: metric_lines(&stage.metrics, format, paint),
        children: vec![],
    }
}

/// Every stage as a tree, each stage under the stage reading from it.
fn stage_tree(stage: &DecodedStage, format: DistributedMetricsFormat, paint: Paint) -> Node {
    let mut node = stage_node(stage, format, paint);
    node.children = (input_stages(stage).into_iter())
        .map(|input| stage_tree(input, format, paint))
        .collect();
    node
}

/// The metrics reported by `stages` and by their nodes, added up by name. Metrics are filtered
/// once decoded, so only the totals of the metrics matching the filters are displayed. Tasks of
/// different stages are unrelated, so the totals are never displayed per task.
fn totals_node(stages: Vec<&DecodedStage>, paint: Paint) -> Node {
    fn collect(plan: &DecodedPlan, totals: &mut MetricsSet) {
        for metric in plan.metrics.iter() {
            totals.push(Arc::clone(metric));
        }
        // The stage a network boundary reads from is one of `stages`, if it is added up.
        for child in &plan.children {
            collect(child, totals);
        }
    }
    let mut totals = MetricsSet::new();
    for stage in stages {
        for metric in stage.metrics.iter() {
            totals.push(Arc::clone(metric));
        }
        if let Some(plan) = &stage.plan {
            collect(plan, &mut totals);
        }
    }
    Node {
        label: paint.stage("Totals"),
        metrics: metric_lines(&totals, DistributedMetricsFormat::Aggregated, paint),
        children: vec![],
    }
}

/// `stage` and every stage it reads from, directly or not.
fn all_stages(stage: &DecodedStage) -> Vec<&DecodedStage> {
    let mut stages = vec![stage];
    for input in input_stages(stage) {
        stages.extend(all_stages(input));
    }
    stages
}

/// The nodes of a stage as a tree. Network boundaries are leaves: the stages they read from are
/// rendered on their own.
fn operator_tree(plan: &DecodedPlan, format: DistributedMetricsFormat, paint: Paint) -> Node {
    if plan.display == LEAF_DISPLAY {
        return leaf_tree(plan, format, paint);
    }
    Node {
        label: paint.operator(&plan.display),
        metrics: metric_lines(&plan.metrics, format, paint),
        children: (plan.children.iter())
            .map(|child| operator_tree(child, format, paint))
            .collect(),
    }
}

/// Like [crate::display_plan_ascii], each `t<i>: …` variant of a
/// [DistributedLeafExec](crate::DistributedLeafExec) shows the metrics of the task that ran it.
/// Aggregated across tasks, they are shown on the leaf instead.
fn leaf_tree(plan: &DecodedPlan, format: DistributedMetricsFormat, paint: Paint) -> Node {
    let (leaf_metrics, by_task) = match format {
        DistributedMetricsFormat::PerTask => (vec![], metrics_by_task_id(&plan.metrics)),
        DistributedMetricsFormat::Aggregated => {
            (metric_lines(&plan.metrics, format, paint), HashMap::new())
        }
    };
    let variant = |task: usize, variant: &DecodedPlan| Node {
        label: paint.operator(&variant.display),
        metrics: by_task
            .get(&task)
            .map(|metrics| metric_lines(metrics, format, paint))
            .unwrap_or_default(),
        children: vec![],
    };
    Node {
        label: paint.operator(&plan.display),
        metrics: leaf_metrics,
        children: (plan.children.iter().enumerate())
            .map(|(task, child)| variant(task, child))
            .collect(),
    }
}

fn find_stage(stage: &DecodedStage, id: u64) -> Option<&DecodedStage> {
    if stage.id == id {
        return Some(stage);
    }
    (input_stages(stage).into_iter()).find_map(|input| find_stage(input, id))
}

/// The stages `stage` reads from, in plan order.
fn input_stages(stage: &DecodedStage) -> Vec<&DecodedStage> {
    fn collect<'a>(plan: &'a DecodedPlan, inputs: &mut Vec<&'a DecodedStage>) {
        inputs.extend(plan.input_stage.as_deref());
        for child in &plan.children {
            collect(child, inputs);
        }
    }
    let mut inputs = vec![];
    if let Some(plan) = &stage.plan {
        collect(plan, &mut inputs);
    }
    inputs
}

/// `Shuffle` for a `[Stage 2] => NetworkShuffleExec: …` node.
fn boundary_kind(display: &str) -> &str {
    let name = display.split_once("=> ").map_or(display, |(_, rest)| rest);
    let name = name.split(':').next().unwrap_or(name);
    name.trim_start_matches("Network").trim_end_matches("Exec")
}

/// One `name=value` line per metric, with per-task values as `name={task:value, …}`. A metric only
/// reported by task 0, like the ones of a plan that is not distributed, displays as `name=value`,
/// and so do all metrics when they are aggregated across tasks.
fn metric_lines(
    metrics: &MetricsSet,
    format: DistributedMetricsFormat,
    paint: Paint,
) -> Vec<String> {
    // Metrics without a task label are added up across tasks when formatted.
    let per_task: HashSet<&str> = match format {
        DistributedMetricsFormat::PerTask => (metrics.iter())
            .filter(|metric| metric_task(metric).is_ok_and(|task| task != 0))
            .map(|metric| metric.value().name())
            .collect(),
        DistributedMetricsFormat::Aggregated => HashSet::new(),
    };
    let mut displayed = MetricsSet::new();
    for metric in metrics.iter() {
        displayed.push(match per_task.contains(metric.value().name()) {
            true => Arc::clone(metric),
            false => without_task_label(metric),
        });
    }
    let mut lines = format_each_metric_by_task(&displayed);
    // The metrics derived for a stage lead its lines, like output_rows and elapsed_compute lead
    // the lines of a node. The sort is stable, so they keep their order.
    lines.sort_by_key(|line| !line.starts_with(STAGE_METRIC_PREFIX));
    lines.iter().map(|metric| paint.metric(metric)).collect()
}

fn without_task_label(metric: &Metric) -> Arc<Metric> {
    let labels = (metric.labels().iter())
        .filter(|label| label.name() != DISTRIBUTED_DATAFUSION_TASK_ID_LABEL)
        .cloned()
        .collect();
    Arc::new(Metric::new_with_labels(
        metric.value().clone(),
        None,
        labels,
    ))
}

/// Where the parameter name that `before` ends with starts, like `mode` in `…, mode`, if it is a
/// whole lowercase word.
fn param_name_start(before: &str) -> Option<usize> {
    let start = (before.char_indices().rev())
        .take_while(|(_, c)| c.is_ascii_lowercase() || *c == '_')
        .last()?
        .0;
    let at_word_start =
        (before[..start].chars().next_back()).is_none_or(|c| !(c.is_alphanumeric() || c == '_'));
    at_word_start.then_some(start)
}

/// Colors the parts of a rendered plan dump with ANSI escape codes when enabled, similar to how
/// code is highlighted. When disabled, text is returned as it is.
#[derive(Debug, Clone, Copy)]
struct Paint(bool);

impl Paint {
    fn style(self, code: &str, text: &str) -> String {
        match self.0 && !text.is_empty() {
            true => format!("\x1b[{code}m{text}\x1b[0m"),
            false => text.to_string(),
        }
    }

    /// Tree guides, task indexes and separators.
    fn dim(self, text: &str) -> String {
        self.style("90", text)
    }

    fn stage(self, text: &str) -> String {
        self.style("1;36", text)
    }

    fn boundary(self, text: &str) -> String {
        self.style("35", text)
    }

    fn value(self, text: &str) -> String {
        self.style("33", text)
    }

    /// A `name=value` metric, with per-task values as `name={task:value, …}`.
    fn metric(self, metric: &str) -> String {
        let Some((name, value)) = metric.split_once('=') else {
            return metric.to_string();
        };
        let value = match value.strip_prefix('{').and_then(|v| v.strip_suffix('}')) {
            Some(tasks) => self.tasks(tasks),
            None => self.value(value),
        };
        format!("{name}{}{value}", self.dim("="))
    }

    /// The `task:value, …` values of a metric for each task, within braces.
    fn tasks(self, tasks: &str) -> String {
        let tasks = (tasks.split(", "))
            .map(|task| match task.split_once(':') {
                Some((index, value)) => {
                    format!("{}{}", self.dim(&format!("{index}:")), self.value(value))
                }
                None => self.value(task),
            })
            .collect::<Vec<_>>()
            .join(&self.dim(", "));
        format!("{}{tasks}{}", self.dim("{"), self.dim("}"))
    }

    /// An operator, like `[Stage 1] => NetworkShuffleExec: input_tasks=3`, with the stage it reads
    /// from, its name and its parameter names highlighted.
    fn operator(self, label: &str) -> String {
        let mut out = String::new();
        let mut rest = label;
        // The `t<i>: ` prefix of the variants of a DistributedLeafExec.
        if let Some((task, after)) = rest.split_once(": ")
            && task.len() > 1
            && task.starts_with('t')
            && task[1..].chars().all(|c| c.is_ascii_digit())
        {
            out += &self.dim(&format!("{task}: "));
            rest = after;
        }
        // The `[Stage N] => ` prefix of network boundaries.
        if rest.starts_with("[Stage ")
            && let Some((input, after)) = rest.split_once(" => ")
        {
            out += &self.stage(input);
            out += &self.dim(" => ");
            rest = after;
        }
        let name_len = rest
            .find(|c: char| !(c.is_alphanumeric() || c == '_'))
            .unwrap_or(rest.len());
        out += &self.style("1;32", &rest[..name_len]);
        out += &self.params(&rest[name_len..]);
        out
    }

    /// Highlights parameter names, like `mode` in `mode=Partitioned`.
    fn params(self, text: &str) -> String {
        let mut out = String::new();
        let mut rest = text;
        while let Some(eq) = rest.find('=') {
            let before = &rest[..eq];
            match param_name_start(before) {
                Some(start) => {
                    out += &before[..start];
                    out += &self.style("34", &before[start..]);
                    out += &self.dim("=");
                }
                None => {
                    out += before;
                    out += "=";
                }
            }
            rest = &rest[eq + 1..];
        }
        out + rest
    }
}

