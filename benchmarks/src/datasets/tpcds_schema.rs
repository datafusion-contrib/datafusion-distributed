#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_tables_have_schemas() {
        for table in [
            "call_center",
            "catalog_page",
            "catalog_returns",
            "catalog_sales",
            "customer",
            "customer_address",
            "customer_demographics",
            "date_dim",
            "household_demographics",
            "income_band",
            "inventory",
            "item",
            "promotion",
            "reason",
            "ship_mode",
            "store",
            "store_returns",
            "store_sales",
            "time_dim",
            "warehouse",
            "web_page",
            "web_returns",
            "web_sales",
            "web_site",
        ] {
            let schema =
                table_schema(table).unwrap_or_else(|| panic!("missing schema for {table}"));
            assert!(
                !schema.fields().is_empty(),
                "{table} schema should not be empty"
            );
        }
        assert!(table_schema("dbgen_version").is_none());
    }
}
